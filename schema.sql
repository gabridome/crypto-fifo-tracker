-- The single source of truth for the database schema is:
--
--     doc/schema.sql
--
-- Everything reads from there: tests/conftest.py and the other test fixtures,
-- setup_demo.py, setup.sh (which prefers it when present), and the migrations
-- in calculators/update_fifo_schema*.py. Nothing in the repo reads this file.
--
-- Until 2026-10-17 this file held a second copy of the DDL. It had drifted:
-- it carried neither transactions.swap_group_id nor swap_lot_transfers, so a
-- database built from it was refused by the FIFO engine's first prerequisite
-- check. The copy was removed rather than updated, because doc/schema.sql
-- carries CHECK constraints that SQLite cannot add by a later ALTER TABLE —
-- a drifted copy is not something a migration can rescue, and two copies
-- already drifted undetected once (task 8 review).
--
-- To build a database:
--
--     sqlite3 data/crypto_fifo.db < doc/schema.sql
--
-- See doc/code_guidelines.md §4.3 (no duplicated logic; one schema source) and
-- doc/project_guidelines.md §"Schema DB".
--
